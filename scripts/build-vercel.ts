/**
 * Build the hosted demo for Vercel (Build Output API v3), then deploy it with `vercel deploy --prebuilt`.
 *
 *   .vercel/output/static/              the Vite app (frontend/dist)
 *   .vercel/output/functions/api/lab.func/
 *     index.mjs                         launcher: points the lab at its assets and /tmp, then loads app.mjs
 *     app.mjs                           the lab API (services/mole/src/lab/app.ts), bundled with esbuild
 *     services/mole/fixtures/**         fixture sources (so trials report the real source size)
 *     services/mole/sandbox/observe.cjs the egress observer preload
 *     prebuilt/services/mole/fixtures/  each fixture bundled to plain JS: the same code, no TypeScript toolchain
 *     prebuilt/services/mole/src/lab/microvm-runner.mjs  the trial runner uploaded into each Vercel Sandbox microVM
 *   .vercel/output/config.json          /lab/* → the function; everything else static
 *
 * Usage:  pnpm build:vercel && vercel deploy --prebuilt [--prod]
 */
import { execSync } from "node:child_process";
import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { bundleOptions } from "../services/mole/src/lab/bundle.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, ".vercel/output");
const FUNC = join(OUT, "functions/api/lab.func");
const FIXTURES = join(ROOT, "services/mole/fixtures");

// Fixture entries the lab spawns. Everything else in fixtures/ is a module they import.
const ENTRIES = ["mailer-mcp/server.ts", "billing-helper-mcp/server.ts", "safe-notes-mcp/server.ts", "helpdesk-copilot/app.ts", "vendors/server.ts"];

const common = bundleOptions;

function step(label: string) { console.log(`\n▸ ${label}`); }
const size = (p: string): number => (statSync(p).isDirectory() ? readdirSync(p).reduce((n, f) => n + size(join(p, f)), 0) : statSync(p).size);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(FUNC, { recursive: true });

step("frontend: vite build");
execSync("pnpm -C frontend build", { cwd: ROOT, stdio: "inherit" });
cpSync(join(ROOT, "frontend/dist"), join(OUT, "static"), { recursive: true });

step("lab API: bundle app.ts + the microVM trial runner");
await build({ ...common, entryPoints: [join(ROOT, "services/mole/src/lab/vercel.ts")], outfile: join(FUNC, "app.mjs") });
await build({ ...common, entryPoints: [join(ROOT, "services/mole/src/lab/microvm-runner.ts")], outfile: join(FUNC, "prebuilt/services/mole/src/lab/microvm-runner.mjs") });

step("fixtures: sources + prebuilt JS");
cpSync(FIXTURES, join(FUNC, "services/mole/fixtures"), { recursive: true });
cpSync(join(ROOT, "services/mole/sandbox/observe.cjs"), join(FUNC, "services/mole/sandbox/observe.cjs"));
for (const e of ENTRIES) {
  const src = join(FIXTURES, e);
  const out = join(FUNC, "prebuilt", relative(ROOT, src).replace(/\.ts$/, ".mjs"));
  await build({ ...common, entryPoints: [src], outfile: out });
  console.log(`  ${relative(ROOT, src)} → ${relative(FUNC, out)}`);
}

writeFileSync(join(FUNC, "index.mjs"), `// Launcher (generated by scripts/build-vercel.ts). Sets where the lab finds its assets and writes data, then loads it.
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
process.env.MOLE_ASSETS ??= dirname(fileURLToPath(import.meta.url));
process.env.MOLE_DATA ??= "/tmp/mole";
let handler;
export default async function lab(req, res) {
  // The route rewrites /lab/<path> to this function; restore the original path if the platform hands us the rewrite.
  const u = new URL(req.url, "http://lab");
  if (!u.pathname.startsWith("/lab/")) {
    const p = u.searchParams.get("__path");
    u.searchParams.delete("__path");
    req.url = "/lab/" + (p ?? "") + (u.search || "");
  }
  // Vercel Sandbox auth: the platform passes this invocation's OIDC token as a header; make it visible to the SDK.
  const oidc = req.headers["x-vercel-oidc-token"];
  if (typeof oidc === "string" && oidc) process.env.VERCEL_OIDC_TOKEN = oidc;
  handler ??= (await import("./app.mjs")).default;
  return handler(req, res);
}
`);
writeFileSync(join(FUNC, "package.json"), JSON.stringify({ type: "module" }));
writeFileSync(join(FUNC, ".vc-config.json"), JSON.stringify({
  runtime: "nodejs22.x", handler: "index.mjs", launcherType: "Nodejs", shouldAddHelpers: false,
  supportsResponseStreaming: true, maxDuration: 300,
}, null, 2));

writeFileSync(join(OUT, "config.json"), JSON.stringify({
  version: 3,
  routes: [
    { src: "^/lab/(.*)$", dest: "/api/lab?__path=$1" },
    { handle: "filesystem" },
  ],
}, null, 2));

step("done");
console.log(`  static   ${(size(join(OUT, "static")) / 1024).toFixed(0)} KB`);
console.log(`  function ${(size(FUNC) / 1024 / 1024).toFixed(1)} MB`);
console.log("  deploy:  vercel deploy --prebuilt        (add --prod for production)");
