import { useState } from "react";
import type { useRun } from "../lib/useRun";
import { Stars } from "../components/Stars";
import { Logo } from "../components/Logo";
import { Mono } from "../components/bits";

export function TrustReport({ run, onStart }: { run: ReturnType<typeof useRun>; onStart: () => void }) {
  const agents = (run.status?.agents ?? []).filter((a) => a.rating);
  const [sel, setSel] = useState<string>("compromised");
  if (!agents.length) {
    return (
      <div className="screen empty-screen">
        <div className="empty">
          <h2>No report yet.</h2>
          <p>A Trust Report is generated for each agent after a crash test — a shareable, evidence-backed safety rating.</p>
          <button className="btn primary" onClick={onStart} disabled={run.starting}>{run.starting ? "Seeding…" : "Start crash test"}</button>
        </div>
      </div>
    );
  }
  const a = agents.find((x) => x.spec.id === sel) ?? agents[0]!;
  const r = a.rating!;
  return (
    <div className="screen report">
      <div className="report-switch">
        {agents.map((x) => (
          <button key={x.spec.id} className={x.spec.id === a.spec.id ? "on" : ""} onClick={() => setSel(x.spec.id)}>{x.spec.role}</button>
        ))}
      </div>

      <article className="report-sheet">
        <header className="report-head">
          <div className="report-brand"><Logo size={20} tripped={r.overallStars < 3} /> Tripwire Trust Report</div>
          <span className="report-date">{new Date().toLocaleDateString()}</span>
        </header>

        <div className="report-title">
          <h1>{a.spec.role}</h1>
          <p className="report-sub">{a.spec.model}{a.spec.skill ? ` · skill: ${a.spec.skill.name}` : ""}</p>
        </div>

        <div className="report-grade">
          <div className="report-gradebox"><span>{r.grade}</span></div>
          <div>
            <Stars value={r.overallStars} size={26} />
            <p className="report-verdict">
              {r.overallStars === 5 ? "Passed every category with no trips." : r.worstSeverity === "critical" ? "Critical: a secret left the boundary." : "Failed one or more safety categories."}
            </p>
          </div>
          <div className="report-util">
            <span className="k">Task utility</span>
            <span className="v">{r.utility.percent}%</span>
            <span className="s">{r.utility.correct}/{r.utility.total} resolved correctly</span>
          </div>
        </div>

        <div className="report-cats">
          {r.categories.map((c) => (
            <div key={c.key} className="report-cat">
              <div className="rc-top"><span>{c.label}</span><Stars value={c.stars} size={14} /></div>
              <p className="rc-blurb">{c.blurb}</p>
              {c.trips.map((t) => <p key={t.tripId} className="rc-trip"><Mono>{t.number}</Mono> {t.headline}</p>)}
            </div>
          ))}
        </div>

        <footer className="report-foot">
          <div className="attr-line">
            <strong>Attribution.</strong> Every finding names the agent, session, and the skill or MCP server responsible —
            and how far the canary got. {a.keewano ? `${a.keewano.accepted} typed events logged to Keewano.` : ""}
          </div>
          <div className="report-sig">Proof, not opinion. Generated by Tripwire from recorded events — no LLM judge.</div>
        </footer>
      </article>
    </div>
  );
}
